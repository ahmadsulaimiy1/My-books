def quran_rows():
    rows = []
    for f in sorted((BOOK / "الافتتاحية").glob("*.md")) + [BOOK / "00-كلمة-المؤلف.md"]:
        loc = CH.get(f.name[:2], "كلمة المؤلف" if f.name.startswith("00-ك") else "التمهيد")
        for m in re.finditer(r"﴿([^﴾]+)﴾\s*(?:\(([^)]+)\))?", f.read_text(encoding="utf-8")):
            words = m.group(1).split()
            text = " ".join(words[:6]) + ("…" if len(words) > 6 else "")
            ref = m.group(2) or "بلا إحالة في المتن"
            rows.append((loc, "قرآن", text, "نص", ref, "مصحف المدينة النبوية، رواية حفص", "", "ثابت النسبة",
                         "مطابقة الرسم والضبط وعلامات الوقف على المصحف" + ("" if m.group(2) else "؛ تُضاف الإحالة")))
    return rows


VIEW = [0, 1, 2, 3, 4, 5, 6, 11, 14, 17]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = quran_rows() + ROWS
    table = []
    for i, (loc, kind, text, form, src, ed, grade, state, note) in enumerate(rows, 1):
        table.append([f"م١-{str(i).zfill(3).translate(AR)}", loc, kind, text, form, src, ed, "", "", "", "", grade, "", "",
                      STATE[state], "", "", note])
    with open(OUT / "سجل-النقول.tsv", "w", encoding="utf-8") as fh:
        fh.write("\t".join(FIELDS) + "\n")
        for r in table:
            fh.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
    counts = {}
    for r in table:
        counts[r[14]] = counts.get(r[14], 0) + 1
    md = ["# السجلّ المركزي للنقول: افتتاحية المجلد الأول", "",
          "يُولَّد من `pdf/ledger.py`. الحقول والحالات في الجزء التاسع من الدليل (الباب ٤٦). "
          "الجزء والصفحة ورقم الحديث فارغةٌ عمدًا حتى تُطابق على الطبعة المعتمدة.", "",
          "**الحالات الآن:** " + "، ".join(f"{k}: {str(v).translate(AR)}" for k, v in counts.items()) + ".",
          "", "**متحقّق:** ٠. فالافتتاحية ما زالت طبعة مراجعة، ولم تعبر البوابة التاسعة. "
          "والحقول الفارغة (المحقّق، والجزء، والصفحة، والرقم، والنص المقارن، والمراجعان) تُملأ عند المطابقة.", "",
          "| " + " | ".join(FIELDS[i] for i in VIEW) + " |", "|" + "---|" * len(VIEW)]
    for r in table:
        md.append("| " + " | ".join(r[i].replace("|", "／") for i in VIEW) + " |")
    (OUT / "سجل-النقول.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(len(table), "entries;", counts)


if __name__ == "__main__":
    main()
