def verdicts(row):
    vid, form, who, src, ed, part, page, state = row[0], row[4], row[5], row[6], row[7], row[9], row[10], row[14]
    seen = vid in L.ON_PRINT
    attr = {"attr": "غير ثابتة: تُنسب بصيغة «يُنسب»", "remove": "لم تثبت"}.get(state, "ثابتة" if seen or page else "عامّة")
    edition = ("المرئيّة: " + L.SCANNED[vid]["edition"]) if vid in L.SCANNED else (
        "المرئيّة (مصوّرة)" if seen else ("نسخةٌ رقمية للطبعة المذكورة" if ed else "—"))
    locus = ("طابق: " + L.SCANNED[vid]["printed"]) if vid in L.SCANNED else (
        "طابق" if seen else (f"من النسخة الرقمية: {page}" if page else "بلا موضع (إحالةٌ عامّة)"))
    kind = form or "—"
    need = NEED.get(vid, "تخدم المسألة في موضعها")
    final = {"ok": "يُثبت", "variant": "يُثبت ويُبيَّن الاختلاف", "attr": "يُثبت بصيغة التمريض",
             "incomplete": "يبقى في سجلّ التوثيق: توثيقٌ ناقص", "remove": "يُعاد النظر في إبقائه",
             "grade": "يُثبت، والحكم لمختصّ"}[state]
    if state == "ok" and not seen:
        final = "يبقى في سجلّ التوثيق: توثيقٌ ناقص"
    return attr, edition, locus, kind, need, final


