def researcher_sample(n=25, seed=20260924):
    """The random researcher test (ch. 80): a reproducible draw from the ledger, about a third hadith and athar,
    a third scholars' texts, the rest verses, poetry and facts; the result columns are left for the researcher."""
    import random
    lines = (OUT / "سجل-النقول.tsv").read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    rows = [dict(zip(head, ln.split("\t"))) for ln in lines[1:]]
    pools = {"حديث وأثر": [r for r in rows if r["النوع"].startswith(("حديث", "أثر"))],
             "نقول العلماء": [r for r in rows if r["النوع"].startswith(("نقل", "دراسة"))],
             "آيات وشعر ومعلومات": [r for r in rows if r["النوع"].startswith(("قرآن", "شعر", "معلومة"))]}
    rng = random.Random(seed)
    k = {"حديث وأثر": n // 3, "نقول العلماء": n // 3}
    k["آيات وشعر ومعلومات"] = n - sum(k.values())
    out = []
    for name, pool in pools.items():
        for r in sorted(rng.sample(pool, min(k[name], len(pool))), key=lambda r: r["الرقم"]):
            out.append((name, r))
    md = ["# اختبار الباحث العشوائي: افتتاحية المجلد الأول (العيّنة الأولى)", "",
          f"عيّنةٌ من {str(len(out)).translate(AR)} إحالة، سُحبت من السجلّ المركزي سحبًا عشوائيًّا قابلًا للإعادة "
          f"(البذرة {str(seed).translate(AR)}): ثلثها أحاديث وآثار، وثلثها نقول علماء، والباقي آياتٌ وشعرٌ ومعلومات "
          "(الدليل، الباب ٨٠). يتتبّعها باحثٌ لم يشارك في التحقيق في الطبعة المعتمدة نفسها، ويملأ العمودين الأخيرين. "
          "فإن وجد خطأً واحدًا في نصٍّ أو نسبة، أو خطأين في موضع، أُعيد تحقيق الفصل كله.", "",
          "| # | الفئة | الرقم | الموضع | النص | المصدر | الجزء/الصفحة | الرقم في المصدر | النتيجة | الباحث والتاريخ |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for i, (name, r) in enumerate(out, 1):
        parts = [x.strip() for x in r["الجزء"].split("؛")] if r["الجزء"] else []
        pages = [x.strip() for x in r["الصفحة"].split("؛")] if r["الصفحة"] else []
        if parts and len(parts) == len(pages):  # pair each volume with its page: «٩/٩١؛ ١/٣٧١»
            where = "؛ ".join(f"{p}/{q}" for p, q in zip(parts, pages))
        else:
            where = "؛ ".join(pages or parts)
        md.append(f"| {str(i).translate(AR)} | {name} | {r['الرقم']} | {r['الموضع']} | {r['النص'][:60]} | {r['المصدر الأوّلي'][:60]} | "
                  f"{where} | {r['رقم الحديث']} |  |  |")
    (OUT / "اختبار-الباحث-العشوائي.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return len(out)


def table(fields, rows, prefix):
    out = []
    for i, r in enumerate(rows, 1):
        out.append([f"{prefix}-{str(i).zfill(2).translate(AR)}"] + list(r))
    return out


def write(name, title, intro, fields, rows, view=None):
    with open(OUT / f"{name}.tsv", "w", encoding="utf-8") as fh:
        fh.write("\t".join(fields) + "\n")
        for r in rows:
            fh.write("\t".join(str(c).replace("\t", " ") for c in r) + "\n")
    view = view or list(range(len(fields)))
    md = [f"# {title}", "", intro, "", "| " + " | ".join(fields[i] for i in view) + " |", "|" + "---|" * len(view)]
    for r in rows:
        md.append("| " + " | ".join(str(r[i]).replace("|", "／") for i in view) + " |")
    (OUT / f"{name}.md").write_text("\n".join(md) + "\n", encoding="utf-8")


