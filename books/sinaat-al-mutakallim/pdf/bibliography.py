def edition_of(entry) -> tuple[str, str, str]:
    """(edition, where the data comes from, status) for one title."""
    g, tier, author, died, title, look, fn, vols, use = entry
    ed, basis, status = "تُحدَّد", "—", "تُحدَّد"
    if look.startswith("sh:"):
        book = look[3:]
        ed, basis = shamela_edition(book)
        status = "معتمدة (الباب ٧٢)" if book in DECIDED else "تُطابق على صفحة العنوان"
    elif look.startswith("sh?"):
        book = shamela_find(title, look[3:], author)
        if book:
            ed, basis = shamela_edition(book)
            status = "تُطابق على صفحة العنوان"
    elif look.startswith("ol"):
        ed, basis = openlibrary(title, author, look[3:] or None)
        status = "تُطابق على صفحة العنوان" if ed else "تُحدَّد"
        ed = ed or "تُحدَّد"
    elif look == "cr":
        ed, basis = crossref(title, author, died if died.isascii() else "")
        status = "طوبقت على Crossref" if ed else "تُحدَّد"
        ed = ed or "تُحدَّد"
    if not ed.strip("، "):
        ed, status = "تُحدَّد", "تُحدَّد"
    if title in ON_SCAN and author in ("ابن جني", "عبد القاهر الجرجاني", "الخطيب القزويني", "أبو هلال العسكري", "الشافعي", "الذهبي", "ابن تيمية"):
        ed, basis, status = ON_SCAN[title], "مصوّرة المطبوع", "طوبقت على مصوّرة المطبوع"
    return ed, basis, status


