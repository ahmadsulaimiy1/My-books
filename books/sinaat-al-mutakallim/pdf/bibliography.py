def _get(url: str) -> str:
    """A catalogue answer, cached; an empty answer is retried and never cached."""
    f = CACHE / hashlib.sha1(url.encode()).hexdigest()
    if f.exists() and f.stat().st_size:
        return f.read_text(encoding="utf-8")
    out = ""
    for attempt in range(3):
        out = subprocess.run(["curl", "-s", "--max-time", "40", url], capture_output=True, text=True).stdout
        if out.strip():
            f.write_text(out, encoding="utf-8")
            break
        time.sleep(2 * (attempt + 1))
    return out


def author_keys(author: str) -> list[str]:
    """The distinctive words of an author's name («أبو عبيد القاسم بن سلام» → عبيد، القاسم، سلام)."""
    return [w for w in S.plain(re.sub(r"\(.*?\)", " ", author)).split() if w not in ("ابن", "ابو", "بن", "عبد", "و", "ال")]


def same_author(author: str, card_author: str) -> bool:
    """Two of the name's distinctive words must be on the card (one, if the name has only one): a single shared
    word such as «القاسم» or «محمد» is not enough."""
    keys, who = author_keys(author), S.plain(card_author)
    need = min(2, len(keys))
    return need == 0 or sum(k in who for k in keys) >= need


def shamela_find(title: str, hint: str, author: str) -> str | None:
    """The Shamela book for a title: a catalogue item whose name holds the title (and the hint, if given) and whose
    card names the author. Titles shared by many books («الأمالي»، «الزهد») are settled by the author."""
    core = re.sub(r"\s*\(.*?\)\s*", " ", title).strip()
    r = json.loads(S._get(f"{S.BASE}/ajax/book/?term=" + urllib.parse.quote(core)) or '{"results":{"items":[]}}')
    items = r.get("results", {}).get("items", [])
    keys = [S.plain(core)] + [S.plain(x) for x in re.findall(r"\((.*?)\)", title)]

    def names(it):  # the catalogue name, and its other name after «=»
        return [S.plain(x) for x in re.split(r"\s=\s", re.sub(r"^كتاب\s+", "", it["text"]))]

    # the title must open the catalogue name (or its other name); a title found inside another book's name is not it
    cands = [it for it in items if any(n.startswith(k) for n in names(it) for k in keys if k)]
    if hint:
        with_hint = [it for it in cands if hint in it["text"]]
        cands = with_hint or cands
    for it in cands[:4]:
        if same_author(author, S.book_card(it["id"]).get("المؤلف", "")):
            return it["id"]
    return None


def shamela_edition(book: str) -> tuple[str, str]:
    c = S.book_card(book)
    parts = [x for x in (("تحقيق " + c["المحقق"]) if c.get("المحقق") else "", c.get("الناشر", ""), c.get("الطبعة", ""),
                          (c.get("عدد الأجزاء", "") + " أجزاء") if c.get("عدد الأجزاء") else "") if x]
    return "، ".join(parts), f"بطاقة المكتبة الشاملة {book}"


def latin(s: str) -> str:
    """A Latin title for comparison: lower case, letters and digits only, no leading article."""
    s = re.sub(r"[^a-z0-9 ]+", " ", s.lower().replace("'", ""))
    s = re.sub(r"\s+", " ", s).strip()
    return re.sub(r"^(the|a|an) ", "", s)


def same_title(ours: str, found: str) -> bool:
    """The record is the title itself: equal, or one is the other with its subtitle."""
    a, b = latin(ours), latin(found)
    if not a or not b:
        return S.plain(ours) == S.plain(found) or S.plain(found).startswith(S.plain(ours))
    return a == b or (b.startswith(a) and len(a) >= 12) or (a.startswith(b) and len(b) >= 0.6 * len(a))


def openlibrary(title: str, author: str, q: str | None = None) -> tuple[str, str]:
    url = "https://openlibrary.org/search.json?" + urllib.parse.urlencode(
        {"q": q} if q else {"title": title, "author": author.split(",")[0].split(" and ")[0].replace(" et al.", ""), "limit": 5})
    try:
        docs = json.loads(_get(url) or "{}").get("docs", [])
    except json.JSONDecodeError:
        return "", ""
    docs = [d for d in docs if q or same_title(title, d.get("title", ""))]
    if not docs:
        return "", ""
    d = docs[0]
    pub = "، ".join((d.get("publisher") or [])[:2])
    return (f"{pub}؛ أول نشر {d.get('first_publish_year', '')}".strip("؛ "), f"Open Library {d.get('key', '')}")


def crossref(title: str, author: str, year: str = "") -> tuple[str, str]:
    """An article's record, only if it is the original publication (same title and same year), not a reprint."""
    url = "https://api.crossref.org/works?" + urllib.parse.urlencode(
        {"query.bibliographic": f"{title} {author} {year}".strip(), "rows": 5})
    try:
        items = json.loads(_get(url) or "{}")["message"]["items"]
    except (json.JSONDecodeError, KeyError):
        return "", ""
    items = [it for it in items if same_title(title, (it.get("title") or [""])[0])
             and (not year or str((it.get("issued", {}).get("date-parts") or [[""]])[0][0]) == year)]
    if not items:
        return "", ""
    it = items[0]
    cont = (it.get("container-title") or [""])[0]
    year = (it.get("issued", {}).get("date-parts") or [[""]])[0][0]
    return (f"{cont} {it.get('volume', '')}({it.get('issue', '')}): {it.get('page', '')}, {year}".replace("()", ""),
            f"Crossref {it.get('DOI', '')}")


